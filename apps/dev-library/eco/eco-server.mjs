export function isEcoHost(req) {
  if (process.env.ECO_HOST_OVERRIDE) return true;
  if (req.headers["x-eco-host"]) return true;
  const host = String(req.headers.host || "").split(":")[0].toLowerCase();
  return host === ECO_HOST;
}

