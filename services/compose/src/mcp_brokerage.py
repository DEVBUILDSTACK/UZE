def _rpc_result(req_id: Any, result: dict[str, Any]) -> JSONResponse:
    return JSONResponse(
        content={"jsonrpc": "2.0", "id": req_id, "result": result}
    )


def _rpc_error(req_id: Any, code: int, message: str) -> JSONResponse:
    return JSONResponse(
        content={
            "jsonrpc": "2.0",
            "id": req_id,
            "error": {"code": code, "message": message},
        }
    )


