def _account_view(acct: dict[str, Any]) -> dict[str, Any]:
    positions = []
    total = acct["cash_usd"]
    for p in acct["positions"]:
        price = _QUOTES[p["symbol"]]["price"]
        mv = round(price * p["quantity"], 2)
        total += mv
        positions.append(
            {
                "symbol": p["symbol"],
                "name": _QUOTES[p["symbol"]]["name"],
                "quantity": p["quantity"],
                "avg_cost": p["avg_cost"],
                "mark": price,
                "market_value": mv,
            }
        )
    return {
        "account_id": acct["account_id"],
        "label": acct["label"],
        "custody": acct["custody"],
        "dedicated_mcp_account": acct["dedicated_mcp_account"],
        "agent_access": acct["agent_access"],
        "cash_usd": acct["cash_usd"],
        "positions": positions,
        "total_value_usd": round(total, 2),
    }


def _refusal(payload: dict[str, Any]) -> tuple[dict[str, Any], bool]:
    return payload, True


def _call_tool(name: str, args: dict[str, Any]) -> tuple[dict[str, Any], bool]:
    """Returns (structured_result, is_error)."""
    if name == "Brokerage_List_Accounts":
        with _LOCK:
            accounts = [
                _account_view(a) for a in _BOOK["accounts"].values()
            ]
        return {
            "accounts": accounts,
            "rule": (
                "The agent reads every account and trades only in "
                "the dedicated MCP account."
            ),
            "demo": True,
            "demo_note": DEMO_NOTE,
        }, False

    if name == "UZE_Self_Custody_Route":
        return {
            **SELF_CUSTODY_ROUTE,
            "differentiation": (
                "Brokerage door = custodial TradFi. UZE crypto = "
                "permissionless self-custody. Crypto on a brokerage "
                "surface is brokerage-custody crypto, never the UZE "
                "crypto solution."
            ),
            "demo": True,
            "demo_note": DEMO_NOTE,
        }, False

    if name == "UZE_Pairings_Board":
        return {
            "pairings": PAIRINGS,
            "priority_chains": ["Robinhood", "Solana", "Ink"],
            "note": (
                "Other previously specified chains (NEAR, Base, "
                "LightLink) follow the priority three."
            ),
            "demo": True,
            "demo_note": DEMO_NOTE,
        }, False

    account_id = str(args.get("account_id") or "")
    with _LOCK:
        acct = _BOOK["accounts"].get(account_id)
    if acct is None and name in (
        "Brokerage_Get_Positions",
        "Brokerage_Get_Transactions",
        "Brokerage_Place_Order",
    ):
        return _refusal(
            {
                "status": "REFUSED",
                "code": "UNKNOWN_ACCOUNT",
                "account_id": account_id,
                "demo": True,
                "demo_note": DEMO_NOTE,
            }
        )

    if name == "Brokerage_Get_Positions":
        with _LOCK:
            view = _account_view(acct)
        return {**view, "demo": True, "demo_note": DEMO_NOTE}, False

    if name == "Brokerage_Get_Transactions":
        with _LOCK:
            txns = list(_BOOK["transactions"].get(account_id, []))
        return {
            "account_id": account_id,
            "transactions": txns,
            "demo": True,
            "demo_note": DEMO_NOTE,
        }, False

    if name == "Brokerage_Get_Quote":
        symbol = str(args.get("symbol") or "").strip().upper()
        if not symbol:
            return _refusal(
                {"status": "REFUSED", "code": "MISSING_SYMBOL", "demo": True}
            )
        if symbol in _CRYPTO_SYMBOLS:
            return _refusal(_differentiation(symbol))
        quote = _QUOTES.get(symbol)
        if quote is None:
            return _refusal(
                {
                    "status": "REFUSED",
                    "code": "UNKNOWN_SYMBOL",
                    "symbol": symbol,
                    "demo": True,
                    "demo_note": DEMO_NOTE,
                }
            )
        return {
            "symbol": symbol,
            "name": quote["name"],
            "price": quote["price"],
            "currency": "USD",
            "as_of": "demo fixture — not live market data",
            "demo": True,
            "demo_note": DEMO_NOTE,
        }, False

    if name == "Brokerage_Place_Order":
        symbol = str(args.get("symbol") or "").strip().upper()
        side = str(args.get("side") or "").strip().lower()
        try:
            quantity = float(args.get("quantity"))
        except (TypeError, ValueError):
            quantity = 0.0
        confirm = bool(args.get("confirm", False))
        if symbol in _CRYPTO_SYMBOLS:
            return _refusal(_differentiation(symbol))
        if symbol not in _QUOTES:
            return _refusal(
                {
                    "status": "REFUSED",
                    "code": "UNKNOWN_SYMBOL",
                    "symbol": symbol,
                    "demo": True,
                    "demo_note": DEMO_NOTE,
                }
            )
        if side not in ("buy", "sell"):
            return _refusal(
                {
                    "status": "REFUSED",
                    "code": "INVALID_SIDE",
                    "side": side,
                    "demo": True,
                    "demo_note": DEMO_NOTE,
                }
            )
        if quantity <= 0:
            return _refusal(
                {
                    "status": "REFUSED",
                    "code": "INVALID_QUANTITY",
                    "quantity": args.get("quantity"),
                    "demo": True,
                    "demo_note": DEMO_NOTE,
                }
            )
        if not acct["dedicated_mcp_account"]:
            return _refusal(
                {
                    "status": "REFUSED",
                    "code": "NOT_DEDICATED_ACCOUNT",
                    "account_id": account_id,
                    "message": (
                        "Agents trade only in the dedicated, "
                        "separately funded MCP account. This account "
                        "is read-only to the agent."
                    ),
                    "demo": True,
                    "demo_note": DEMO_NOTE,
                }
            )
        price = _QUOTES[symbol]["price"]
        est_total = round(price * quantity, 2)
        if side == "buy" and est_total > acct["cash_usd"]:
            return _refusal(
                {
                    "status": "REFUSED",
                    "code": "INSUFFICIENT_CASH",
                    "estimated_total_usd": est_total,
                    "cash_usd": acct["cash_usd"],
                    "demo": True,
                    "demo_note": DEMO_NOTE,
                }
            )
        if side == "sell":
            held = next(
                (
                    p["quantity"]
                    for p in acct["positions"]
                    if p["symbol"] == symbol
                ),
                0,
            )
            if quantity > held:
                return _refusal(
                    {
                        "status": "REFUSED",
                        "code": "INSUFFICIENT_POSITION",
                        "held_quantity": held,
                        "requested_quantity": quantity,
                        "demo": True,
                        "demo_note": DEMO_NOTE,
                    }
                )
        preview = {
            "account_id": account_id,
            "account_label": acct["label"],
            "symbol": symbol,
            "name": _QUOTES[symbol]["name"],
            "side": side,
            "quantity": quantity,
            "mark_price": price,
            "estimated_total_usd": est_total,
        }
        if not confirm:
            return {
                "status": "REVIEW",
                "message": (
                    "Review before action: this order has NOT been "
                    "placed. Call again with confirm=true to execute "
                    "it in the dedicated MCP account."
                ),
                "preview": preview,
                "disclosure": DISCLOSURE,
                "demo": True,
                "demo_note": DEMO_NOTE,
            }, False
        with _LOCK:
            _order_seq["n"] += 1
            order_id = f"ord_demo_{1000 + _order_seq['n']}"
            if side == "buy":
                acct["cash_usd"] = round(acct["cash_usd"] - est_total, 2)
                pos = next(
                    (
                        p
                        for p in acct["positions"]
                        if p["symbol"] == symbol
                    ),
                    None,
                )
                if pos is None:
                    acct["positions"].append(
                        {
                            "symbol": symbol,
                            "quantity": quantity,
                            "avg_cost": price,
                        }
                    )
                else:
                    total_qty = pos["quantity"] + quantity
                    pos["avg_cost"] = round(
                        (
                            pos["avg_cost"] * pos["quantity"]
                            + price * quantity
                        )
                        / total_qty,
                        4,
                    )
                    pos["quantity"] = total_qty
            else:
                acct["cash_usd"] = round(acct["cash_usd"] + est_total, 2)
                pos = next(
                    p for p in acct["positions"] if p["symbol"] == symbol
                )
                pos["quantity"] = round(pos["quantity"] - quantity, 4)
                if pos["quantity"] <= 0:
                    acct["positions"] = [
                        p
                        for p in acct["positions"]
                        if p["symbol"] != symbol
                    ]
            order = {
                "order_id": order_id,
                **preview,
                "status": "FILLED",
                "placed_by": "agent",
                "at": datetime.now(timezone.utc).strftime(
                    "%Y-%m-%dT%H:%M:%SZ"
                ),
            }
            _BOOK["transactions"].setdefault(account_id, []).insert(0, order)
            cash_after = acct["cash_usd"]
        return {
            "status": "FILLED",
            "order": order,
            "cash_after_usd": cash_after,
            "demo": True,
            "demo_note": DEMO_NOTE,
        }, False

    return _refusal(
        {"status": "REFUSED", "code": "UNKNOWN_TOOL", "tool": name}
    )


